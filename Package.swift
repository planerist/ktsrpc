// swift-tools-version: 5.9
import PackageDescription

// KtsRpc: the Swift client runtime of kts-rpc. The typed client (`Rpc` types and `RpcClient`
// methods) is generated from the Kotlin RPC interfaces by rpc-gen's SwiftRpcExporter.
// Builds for macOS too, so the tests run with `swift test`, without a simulator.
let package = Package(
    name: "KtsRpc",
    platforms: [.iOS(.v16), .macOS(.v13)],
    products: [
        .library(name: "KtsRpc", targets: ["KtsRpc"]),
    ],
    targets: [
        .target(name: "KtsRpc", path: "swift/Sources/KtsRpc"),
        .testTarget(name: "KtsRpcTests", dependencies: ["KtsRpc"], path: "swift/Tests/KtsRpcTests"),

        // The example server's client (generated by `./gradlew examples:schema:generateSwiftRpc`)
        // and its tests against the running server (examples/ktor-server).
        .target(name: "ExampleRpc", dependencies: ["KtsRpc"], path: "examples/swift/Sources/ExampleRpc"),
        .testTarget(name: "ExampleRpcTests", dependencies: ["ExampleRpc"], path: "examples/swift/Tests/ExampleRpcTests"),
    ]
)
