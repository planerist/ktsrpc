package net.planerist.ktsrpc.gen.swiftGenerator

import kotlinx.serialization.ExperimentalSerializationApi
import kotlinx.serialization.SerialName
import kotlinx.serialization.descriptors.SerialDescriptor
import kotlinx.serialization.serializerOrNull
import java.time.OffsetDateTime
import kotlin.reflect.KClass
import kotlin.reflect.KFunction
import kotlin.reflect.KParameter
import kotlin.reflect.KType
import kotlin.reflect.full.declaredFunctions
import kotlin.reflect.full.findAnnotation
import kotlin.reflect.full.findAnnotations
import kotlin.reflect.full.isSubclassOf
import kotlin.reflect.full.memberProperties
import kotlin.reflect.full.primaryConstructor
import kotlin.reflect.full.starProjectedType

/**
 * Swift client generator.
 *
 * Emits Codable types for every class the RPC interfaces use (in the `Rpc` namespace) and typed
 * methods on `RpcClient`; both come from the KtsRpc Swift package (`swift/`). Wire names,
 * optionality and sealed-class discriminators come from kotlinx.serialization descriptors; Swift
 * types come from Kotlin reflection.
 *
 * Forward compatibility: enums and sealed hierarchies decode unknown values into `.unknown`, and
 * fields with Kotlin default values are optional, since a server with `encodeDefaults = false`
 * omits them.
 *
 * @param rpcClasses The RPC interfaces.
 * @param mappings Kotlin classes with hand-written Swift counterparts, mapped to the qualified
 *   Swift type name. [defaultMappings] covers the date types of the Swift package.
 * @param contextAnnotation The annotation of the parameter the server fills with the request
 *   context (`RpcCallHandler.contextAnnotation`). A parameter named `context` is left out too, as
 *   in the TypeScript client.
 * @param runtimeModule The Swift module to import the runtime from; null when the generated file
 *   is compiled into that module.
 * @param classDiscriminator The `Json.classDiscriminator` of the server.
 */
@OptIn(ExperimentalSerializationApi::class)
class SwiftGenerator(
    private val rpcClasses: List<KClass<*>>,
    private val mappings: Map<KClass<*>, String> = defaultMappings,
    private val contextAnnotation: KClass<out Annotation>? = null,
    private val runtimeModule: String? = "KtsRpc",
    private val classDiscriminator: String = "type",
) {
    private val functions = rpcClasses.flatMap { it.declaredFunctions }.sortedBy { it.name }

    private val classes = closure(
        functions.flatMap { func -> rpcParameters(func).map { it.type } + func.returnType }
    ).sortedBy { swiftName(it) }

    init {
        val duplicates = classes.groupBy { swiftName(it) }.filter { it.value.size > 1 }
        require(duplicates.isEmpty()) { "Swift type name clash: ${duplicates.keys}" }
        val overloads = functions.groupBy { it.name }.filter { it.value.size > 1 }
        require(overloads.isEmpty()) { "RPC method name clash: ${overloads.keys}" }
    }

    val text: String
        get() = buildString {
            appendLine("// Generated by kts-rpc (SwiftRpcExporter) from the Kotlin RPC interfaces. Do not edit.")
            appendLine()
            appendLine("import Foundation")
            runtimeModule?.let { appendLine("import $it") }
            appendLine()
            appendLine("extension Rpc {")
            appendLine(classes.joinToString("\n\n") { generateType(it) }.indented())
            appendLine("}")
            appendLine()
            appendLine("extension Rpc {")
            appendLine("    enum Args {")
            appendLine(functions.filter { rpcParameters(it).isNotEmpty() }
                .joinToString("\n\n") { generateArgs(it) }.indented(2))
            appendLine("    }")
            appendLine("}")
            appendLine()
            appendLine("extension RpcClient {")
            appendLine(functions.joinToString("\n\n") { generateMethod(it) }.indented())
            appendLine("}")
        }

    // Types

    /** Every class reachable from [roots] through property types, type arguments and sealed subclasses. */
    private fun closure(roots: List<KType>): Set<KClass<*>> {
        val result = linkedSetOf<KClass<*>>()
        val visited = mutableSetOf<KClass<*>>()
        val queue = ArrayDeque<KClass<*>>()

        fun enqueue(type: KType) {
            (type.classifier as? KClass<*>)?.let { queue.add(it) }
            type.arguments.forEach { argument -> argument.type?.let { enqueue(it) } }
        }

        roots.forEach { enqueue(it) }
        while (queue.isNotEmpty()) {
            val klass = queue.removeFirst()
            if (!visited.add(klass)) continue
            if (klass.isValue && klass !in mappings) {
                enqueue(underlyingType(klass))
                continue
            }
            if (!isGenerated(klass)) continue
            result.add(klass)
            queue.addAll(klass.sealedSubclasses)
            klass.memberProperties.forEach { enqueue(it.returnType) }
        }
        return result
    }

    private fun isGenerated(klass: KClass<*>): Boolean {
        val name = klass.qualifiedName ?: return false
        return klass !in mappings &&
            klass !in rpcClasses &&
            klass != Unit::class &&
            !klass.isValue &&
            !klass.isSubclassOf(Iterable::class) &&
            !klass.isSubclassOf(Map::class) &&
            !name.startsWith("kotlin.") &&
            !name.startsWith("kotlinx.")
    }

    /** A value class is serialized as its one property. */
    private fun underlyingType(klass: KClass<*>): KType =
        klass.primaryConstructor?.parameters?.singleOrNull()?.type
            ?: error("${klass.qualifiedName}: a value class needs one constructor parameter")

    private fun generateType(klass: KClass<*>): String =
        when {
            klass.java.isEnum -> generateEnum(klass)
            klass.isSealed -> generateSealed(klass)
            else -> generateStruct(klass)
        }

    private class Field(val wireName: String, val ident: String, val type: KType, val optional: Boolean) {
        /** Absent only because it has a default: left out when nil instead of sent as null. */
        val omittable = optional && !type.isMarkedNullable
    }

    private fun fields(klass: KClass<*>): List<Field> {
        val descriptor = descriptor(klass)
        val properties = klass.memberProperties.associateBy { it.findAnnotation<SerialName>()?.value ?: it.name }
        return (0 until descriptor.elementsCount).map { i ->
            val name = descriptor.getElementName(i)
            val property = properties[name]
                ?: error("${klass.qualifiedName}.$name: serial name does not match a property")
            Field(
                wireName = name,
                ident = identifier(property.name),
                type = property.returnType,
                optional = property.returnType.isMarkedNullable || descriptor.isElementOptional(i),
            )
        }
    }

    private fun generateStruct(klass: KClass<*>): String {
        val name = swiftName(klass)
        val fields = fields(klass)
        if (fields.isEmpty()) {
            return """
                |public struct $name: Codable, Hashable, Sendable {
                |    public init() {}
                |}
            """.trimMargin()
        }

        fun fieldType(f: Field) = swiftType(f.type, nullable = false) + if (f.optional) "?" else ""

        return buildString {
            appendLine("public struct $name: Codable, Hashable, Sendable {")
            fields.forEach { appendLine("    public var ${it.ident}: ${fieldType(it)}") }
            appendLine()
            appendLine("    public init(")
            appendLine(fields.joinToString(",\n") {
                "        ${it.ident}: ${fieldType(it)}" + if (it.optional) " = nil" else ""
            })
            appendLine("    ) {")
            fields.forEach { appendLine("        self.${it.ident} = ${it.ident}") }
            appendLine("    }")
            appendLine()
            appendLine("    private enum CodingKeys: String, CodingKey {")
            fields.forEach { appendLine("        case ${it.ident} = \"${it.wireName}\"") }
            appendLine("    }")
            appendLine()
            appendLine("    public init(from decoder: Decoder) throws {")
            appendLine("        let c = try decoder.container(keyedBy: CodingKeys.self)")
            fields.forEach {
                val decode = if (it.optional) "decodeIfPresent" else "decode"
                appendLine(
                    "        self.${it.ident} = try c.$decode(${swiftType(it.type, nullable = false)}.self, forKey: .${it.ident})"
                )
            }
            appendLine("    }")
            appendLine()
            appendLine("    public func encode(to encoder: Encoder) throws {")
            appendLine("        var c = encoder.container(keyedBy: CodingKeys.self)")
            fields.forEach {
                val encode = if (it.omittable) "encodeIfPresent" else "encode"
                appendLine("        try c.$encode(self.${it.ident}, forKey: .${it.ident})")
            }
            appendLine("    }")
            append("}")
        }
    }

    private fun generateEnum(klass: KClass<*>): String {
        val name = swiftName(klass)
        val descriptor = descriptor(klass)
        val values = (0 until descriptor.elementsCount).map { descriptor.getElementName(it) }
        val cases = values.map { it to identifier(lowerFirst(it)).let { c -> if (c == "unknown") "unknownValue" else c } }

        return buildString {
            appendLine("public enum $name: Hashable, Sendable, RawRepresentable, Codable {")
            cases.forEach { (_, case) -> appendLine("    case $case") }
            appendLine("    /// A value added to the server after this client was built.")
            appendLine("    case unknown(String)")
            appendLine()
            appendLine("    public static let knownCases: [$name] = [${cases.joinToString { ".${it.second}" }}]")
            appendLine()
            appendLine("    public init(rawValue: String) {")
            appendLine("        switch rawValue {")
            cases.forEach { (value, case) -> appendLine("        case \"$value\": self = .$case") }
            appendLine("        default: self = .unknown(rawValue)")
            appendLine("        }")
            appendLine("    }")
            appendLine()
            appendLine("    public var rawValue: String {")
            appendLine("        switch self {")
            cases.forEach { (value, case) -> appendLine("        case .$case: return \"$value\"") }
            appendLine("        case .unknown(let value): return value")
            appendLine("        }")
            appendLine("    }")
            appendLine()
            appendLine("    public init(from decoder: Decoder) throws {")
            appendLine("        self.init(rawValue: try decoder.singleValueContainer().decode(String.self))")
            appendLine("    }")
            appendLine()
            appendLine("    public func encode(to encoder: Encoder) throws {")
            appendLine("        var c = encoder.singleValueContainer()")
            appendLine("        try c.encode(rawValue)")
            appendLine("    }")
            append("}")
        }
    }

    private fun leafSubclasses(klass: KClass<*>): List<KClass<*>> =
        klass.sealedSubclasses.flatMap { if (it.isSealed) leafSubclasses(it) else listOf(it) }
            .sortedBy { swiftName(it) }

    private fun generateSealed(klass: KClass<*>): String {
        val name = swiftName(klass)
        val subclasses = leafSubclasses(klass).map { Triple(serialName(it), swiftName(it), identifier(lowerFirst(swiftName(it)))) }

        return buildString {
            appendLine("public enum $name: Codable, Hashable, Sendable {")
            subclasses.forEach { (_, type, case) -> appendLine("    case $case(Rpc.$type)") }
            appendLine("    /// A subtype added to the server after this client was built.")
            appendLine("    case unknown(type: String)")
            appendLine()
            appendLine("    private enum TypeKey: String, CodingKey {")
            appendLine("        case type = \"$classDiscriminator\"")
            appendLine("    }")
            appendLine()
            appendLine("    public init(from decoder: Decoder) throws {")
            appendLine("        let type = try decoder.container(keyedBy: TypeKey.self).decode(String.self, forKey: .type)")
            appendLine("        switch type {")
            subclasses.forEach { (serial, type, case) ->
                appendLine("        case \"$serial\": self = .$case(try Rpc.$type(from: decoder))")
            }
            appendLine("        default: self = .unknown(type: type)")
            appendLine("        }")
            appendLine("    }")
            appendLine()
            appendLine("    public func encode(to encoder: Encoder) throws {")
            appendLine("        var c = encoder.container(keyedBy: TypeKey.self)")
            appendLine("        switch self {")
            subclasses.forEach { (serial, _, case) ->
                appendLine("        case .$case(let value):")
                appendLine("            try c.encode(\"$serial\", forKey: .type)")
                appendLine("            try value.encode(to: encoder)")
            }
            appendLine("        case .unknown(let type):")
            appendLine("            throw EncodingError.invalidValue(type, EncodingError.Context(")
            appendLine("                codingPath: encoder.codingPath, debugDescription: \"Unknown $name subtype \\(type)\"))")
            appendLine("        }")
            appendLine("    }")
            append("}")
        }
    }

    // RPC methods

    private fun rpcParameters(func: KFunction<*>): List<KParameter> =
        func.parameters
            .filter { it.kind == KParameter.Kind.VALUE }
            .filter { it.name != "context" }
            .filter { contextAnnotation == null || it.findAnnotations(contextAnnotation).isEmpty() }

    private fun isFlow(func: KFunction<*>) =
        (func.returnType.classifier as KClass<*>).qualifiedName == "kotlinx.coroutines.flow.Flow"

    private fun argsName(func: KFunction<*>) = upperFirst(func.name)

    // A default value doesn't make a parameter optional: RpcCallHandler passes null, not the
    // default, for an argument that is left out.
    private fun argType(param: KParameter) = swiftType(param.type)

    private fun generateArgs(func: KFunction<*>): String {
        val params = rpcParameters(func)
        return buildString {
            appendLine("struct ${argsName(func)}: Encodable, Sendable {")
            params.forEach { appendLine("    let ${identifier(it.name!!)}: ${argType(it)}") }
            appendLine()
            appendLine("    private enum CodingKeys: String, CodingKey {")
            params.forEach { appendLine("        case ${identifier(it.name!!)} = \"${it.name}\"") }
            appendLine("    }")
            appendLine()
            appendLine("    // Nil arguments are sent as explicit nulls, like the TypeScript client does.")
            appendLine("    func encode(to encoder: Encoder) throws {")
            appendLine("        var c = encoder.container(keyedBy: CodingKeys.self)")
            params.forEach { appendLine("        try c.encode(${identifier(it.name!!)}, forKey: .${identifier(it.name!!)})") }
            appendLine("    }")
            append("}")
        }
    }

    private fun generateMethod(func: KFunction<*>): String {
        val params = rpcParameters(func)
        val signature = params.joinToString(", ") {
            val ident = identifier(it.name!!)
            "$ident: ${argType(it)}" + if (it.type.isMarkedNullable) " = nil" else ""
        }
        val args =
            if (params.isEmpty()) "RpcNoArgs()"
            else "Rpc.Args.${argsName(func)}(" + params.joinToString(", ") {
                identifier(it.name!!).let { ident -> "$ident: $ident" }
            } + ")"

        return if (isFlow(func)) {
            val element = swiftType(func.returnType.arguments[0].type!!)
            """
                |public func ${func.name}($signature) -> AsyncThrowingStream<$element, Error> {
                |    transport.subscribe("${func.name}", $args, returning: $element.self)
                |}
            """.trimMargin()
        } else if (func.returnType.classifier == Unit::class) {
            """
                |public func ${func.name}($signature) async throws {
                |    _ = try await transport.call("${func.name}", $args, returning: RpcEmpty.self)
                |}
            """.trimMargin()
        } else {
            val result = swiftType(func.returnType)
            """
                |public func ${func.name}($signature) async throws -> $result {
                |    try await transport.call("${func.name}", $args, returning: $result.self)
                |}
            """.trimMargin()
        }
    }

    // Type names

    private fun swiftType(type: KType, nullable: Boolean = type.isMarkedNullable): String {
        val classifier = type.classifier as? KClass<*> ?: error("Unsupported type $type")
        val base = mappings[classifier] ?: when (classifier) {
            String::class, Char::class -> "String"
            Boolean::class -> "Bool"
            Int::class, Long::class, Short::class, Byte::class -> "Int"
            UInt::class, ULong::class -> "UInt64"
            Double::class -> "Double"
            Float::class -> "Float"
            else -> when {
                classifier.isValue -> swiftType(underlyingType(classifier), nullable = false)
                classifier.isSubclassOf(Map::class) ->
                    "[${swiftType(type.arguments[0].type!!)}: ${swiftType(type.arguments[1].type!!)}]"

                classifier.isSubclassOf(Iterable::class) -> "[${swiftType(type.arguments[0].type!!)}]"
                else -> "Rpc.${swiftName(classifier)}"
            }
        }
        return if (nullable) "$base?" else base
    }

    private fun descriptor(klass: KClass<*>): SerialDescriptor =
        serializerOrNull(klass.starProjectedType)?.descriptor
            ?: error("${klass.qualifiedName} has no serializer: make it @Serializable or map it to a Swift type")

    private fun serialName(klass: KClass<*>) = descriptor(klass).serialName

    // Same naming as the TypeScript client: the serial name, or the class name when the serial
    // name is the default (qualified) one.
    private fun swiftName(klass: KClass<*>): String =
        serializerOrNull(klass.starProjectedType)?.descriptor?.serialName
            ?.takeIf { !it.contains(".") }
            ?: klass.simpleName!!

    companion object {
        /** The date types of the Swift package (`RpcScalars.swift`), kept as the strings the server sends. */
        val defaultMappings: Map<KClass<*>, String> = mapOf(
            OffsetDateTime::class to "Rpc.OffsetDateTime",
            kotlinx.datetime.LocalDate::class to "Rpc.LocalDate",
            kotlin.time.Instant::class to "Rpc.Instant",
        )

        private val keywords = setOf(
            "associatedtype", "class", "deinit", "enum", "extension", "fileprivate", "func",
            "import", "init", "inout", "internal", "let", "open", "operator", "private",
            "precedencegroup", "protocol", "public", "rethrows", "static", "struct", "subscript",
            "typealias", "var", "break", "case", "catch", "continue", "default", "defer", "do",
            "else", "fallthrough", "for", "guard", "if", "in", "repeat", "return", "throw",
            "switch", "where", "while", "Any", "as", "await", "false", "is", "nil", "self",
            "Self", "super", "throws", "true", "try",
        )

        private fun identifier(name: String) = if (name in keywords) "`$name`" else name

        private fun lowerFirst(s: String) = s.replaceFirstChar { it.lowercaseChar() }

        private fun upperFirst(s: String) = s.replaceFirstChar { it.uppercaseChar() }

        private fun String.indented(levels: Int = 1): String =
            lines().joinToString("\n") { if (it.isBlank()) "" else "    ".repeat(levels) + it }
    }
}
